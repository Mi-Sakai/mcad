/// 幾何述語で用いる基準となる相対イプシロン。
///
/// # 値の根拠
///
/// `f64` の機械イプシロン（`f64::EPSILON` ≒ 2.22e-16）は、内積・外積のような
/// 座標の積を伴う計算では丸め誤差が桁上がりする。座標の絶対値が最大でも
/// 1e6 程度（一般的な図面のワールド寸法）だと仮定すると、積の相対誤差は
/// おおよそ `座標^2 * f64::EPSILON` ≒ 1e12 * 2.22e-16 ≒ 2e-4（絶対値）まで
/// 膨らみ得る。これを相対イプシロンに換算すると 1e-9 程度が
/// 「機械誤差より十分大きく、かつ意味のある最小フィーチャ寸法より十分小さい」
/// 安全域に収まる。
///
/// この値は以下の用途で **相対的に** 用いる（絶対値そのままでは使わない）:
/// - 長さ・距離・半径のような次元を持つ量: [`rel_tol`] / [`point_tol`] を通す
/// - 平行判定: `|cross(r, s)| <= EPS * |r| * |s|`（= 角の sin が EPS 未満）
/// - パラメータ [0, 1] 空間の境界許容: 無次元なので `EPS` を直接使用
/// - 角度（ラジアン）許容: 一様な拡大縮小で不変なので `EPS` を直接使用
///   （半径 R に対し弧長 `EPS * R` 相当で、もともと寸法に対して相対的）
pub const EPS: f64 = 1e-9;

/// 大きさ `scale` の量に対する相対許容量 `EPS * (1 + |scale|)`。
///
/// # なぜ絶対 `EPS` ではだめか
///
/// 長さ・距離・半径のような **次元を持つ** 量を絶対値 `EPS` と直接比べると、
/// 図面のワールド寸法が極端（1e-6〜1e6）なときに判定が破綻する:
///
/// - 座標が大きいと、点の減算で生じる丸め誤差（およそ `座標 * f64::EPSILON`）が
///   `EPS` を上回り、本来「同じ点」であるものが別の点として残る。逆に、点どうしの
///   一致許容量より短い「長さ」を非退化と誤認して、下流で 0 除算寸前の計算をする。
/// - 座標が小さいと `EPS` が意味のあるフィーチャ寸法へ近づき、非退化な図形を
///   退化扱いにしうる。
///
/// `scale` には判定に関わる座標・寸法の大きさ（複数あれば和）を渡す。定数項 `1.0` は
/// 原点近傍でも許容量が 0 へ潰れないための下限で、「ワールド単位 1 のオーダーの図面」を
/// 既定スケールとみなすことに相当する。
///
/// # 使わない場所
///
/// - 無次元のパラメータ空間（線分の `t ∈ [0, 1]`）の境界許容 → [`EPS`] を直接。
/// - 角度（ラジアン）の許容 → [`EPS`] を直接。角度は一様な拡大縮小に対して不変なので
///   相対化の必要がない。
/// - 平行・共線判定 → `EPS * |r| * |s|`（なす角の sin）。これも既に相対形。
///
/// # 平行移動に対する非不変性（意図したトレードオフ）
///
/// この許容量は **一様な拡大縮小に対しては不変** だが、**平行移動に対しては不変では
/// ない**: 同じ図形を原点から遠ざけるほど許容量が粗くなる（生の丸め誤差
/// `座標 * f64::EPSILON` よりはるかに大きい「モデリング許容量」として振る舞う）。
/// これは以下を根拠に意図的に受け入れている（Codex adversarial review 2026-08-02 の
/// 指摘への回答。DESIGN.md M8 設計判断9 の実装時追記も参照）:
///
/// - 設計範囲（[`EPS`] doc の |座標| ≤ 1e6）内の最悪許容量は ≈ 1µm（2e-3mm）で、
///   製図上の最小有意寸法（0.01mm）を常に下回る。誤併合が起きるのは「原点から
///   1km 離れた位置にあるサブ µm の真の特徴」に限られる。
/// - 用紙は原点に固定される（M8 設計判断2）ため、通常のワークフローで図形が
///   大オフセットへ到達しない。
/// - 許容量を丸め誤差（ULP）水準へ絞ると、連鎖演算（交点→トリム→フィレット等、
///   near-parallel 交点は条件数依存で誤差が増幅される）への頑健性が下がる。
///   モデリング許容量が生の丸め誤差より粗いのは CAD カーネル一般の慣行。
///
/// 大座標運用（測量座標系のような原点から遠い作図）が将来要件化した場合は、
/// 特徴寸法（辺長・半径）ベース + ULP 座標項の平行移動不変なモデルへ再設計する。
#[inline]
#[must_use]
pub fn rel_tol(scale: f64) -> f64 {
    EPS * (1.0 + scale.abs())
}

/// 2 点の一致判定・差ベクトルの退化判定に用いる相対許容量
/// （`EPS * (1 + |p| + |q|)`、`p`・`q` は原点からの位置ベクトルの長さ）。
///
/// `p - q` の丸め誤差は両点の絶対値に比例して増えるため、両方の大きさを足し合わせた
/// ものを [`rel_tol`] のスケールとして渡す。`intersect` の重複点除去・`split` の
/// 端点近接判定が以前から使っていた形を、そのまま関数として切り出したもの。
#[inline]
#[must_use]
pub fn point_tol(p: Point2, q: Point2) -> f64 {
    rel_tol(p.to_vec2().length() + q.to_vec2().length())
}
